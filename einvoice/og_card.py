# Stroke width as a fraction of cap height. 0.105 is the value that stayed
# legible when the card was rendered and inspected at 26px cap (the eyebrow
# line): thinner strokes vanished into the dark background, thicker ones closed
# up the counters of ``e`` and ``a``.
STROKE_EM = 0.105


def text_width(text, size, tracking=0.0):
    """Advance width in pixels of ``text`` at cap height ``size``.

    ``tracking`` is extra letter spacing in em, applied BETWEEN glyphs (not
    after the last one), so a centred or right-aligned run measures correctly.
    """
    if not text:
        return 0.0
    total = sum(GLYPHS[ch][0] for ch in text)
    return (total + tracking * (len(text) - 1)) * size


class Canvas:
    """An RGB8 raster with a flat background colour, composited in place."""

    def __init__(self, width, height, background):
        self.width = width
        self.height = height
        self.buf = bytearray(bytes(background) * (width * height))

    def fill_rect(self, x, y, w, h, color):
        """Opaque axis-aligned rectangle (used for the accent rules)."""
        x0, y0 = max(0, int(x)), max(0, int(y))
        x1 = min(self.width, int(x + w))
        y1 = min(self.height, int(y + h))
        row = bytes(color) * max(0, x1 - x0)
        for py in range(y0, y1):
            off = (py * self.width + x0) * 3
            self.buf[off:off + len(row)] = row

    def composite(self, coverage, color):
        """Blend ``color`` into the raster at the given {index: alpha} map."""
        buf = self.buf
        cr, cg, cb = color
        for idx, a in coverage.items():
            if a <= 0.0:
                continue
            if a > 1.0:
                a = 1.0
            o = idx * 3
            buf[o] = int(buf[o] + (cr - buf[o]) * a + 0.5)
            buf[o + 1] = int(buf[o + 1] + (cg - buf[o + 1]) * a + 0.5)
            buf[o + 2] = int(buf[o + 2] + (cb - buf[o + 2]) * a + 0.5)


def _stroke(coverage, width, height, x1, y1, x2, y2, half):
    """Accumulate round-capped-segment coverage into ``coverage`` (max-blend).

    Coverage of a pixel centre is ``half + 0.5 - distance``, clamped to [0, 1]:
    a one-pixel-wide analytic ramp at the stroke edge, which is what makes the
    curves read as curves instead of stairs. Only the segment's bounding box
    (grown by ``half + 1``) is visited, so cost is proportional to inked area.
    """
    pad = half + 1.0
    lo_x = max(0, int(math.floor(min(x1, x2) - pad)))
    hi_x = min(width - 1, int(math.ceil(max(x1, x2) + pad)))
    lo_y = max(0, int(math.floor(min(y1, y2) - pad)))
    hi_y = min(height - 1, int(math.ceil(max(y1, y2) + pad)))
    if lo_x > hi_x or lo_y > hi_y:
        return
    dx = x2 - x1
    dy = y2 - y1
    dd = dx * dx + dy * dy
    edge = half + 0.5
    for py in range(lo_y, hi_y + 1):
        fy = py + 0.5 - y1
        base = py * width
        for px in range(lo_x, hi_x + 1):
            fx = px + 0.5 - x1
            if dd > 0.0:
                t = (fx * dx + fy * dy) / dd
                if t < 0.0:
                    t = 0.0
                elif t > 1.0:
                    t = 1.0
            else:
                t = 0.0
            ox = fx - t * dx
            oy = fy - t * dy
            a = edge - math.sqrt(ox * ox + oy * oy)
            if a <= 0.0:
                continue
            if a > 1.0:
                a = 1.0
            idx = base + px
            if a > coverage.get(idx, 0.0):
                coverage[idx] = a


def draw_text(canvas, text, x, baseline, size, color, tracking=0.0):
    """Draw ``text`` with its cap height at ``size`` px, left edge at ``x``.

    ``baseline`` is the device y of the em box's ``y=0`` line (y grows DOWN on
    the canvas, UP in the em box, hence the sign flip). Returns the pen x after
    the run. Raises ``KeyError`` on a character with no glyph.
    """
    half = STROKE_EM * size / 2.0
    coverage = {}
    pen = float(x)
    for i, ch in enumerate(text):
        advance, paths = GLYPHS[ch]
        for path in paths:
            prev = None
            for (gx, gy) in path:
                cur = (pen + gx * size, baseline - gy * size)
                if prev is not None:
                    _stroke(coverage, canvas.width, canvas.height,
                            prev[0], prev[1], cur[0], cur[1], half)
                prev = cur
        pen += advance * size
        if i != len(text) - 1:
            pen += tracking * size
    canvas.composite(coverage, color)
    return pen


