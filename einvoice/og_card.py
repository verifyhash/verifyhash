# PNG encoding. Colour type 2 (truecolour, 8 bit), one IDAT, no ancillary
# chunks. Filters are chosen per scanline by the standard minimum-sum-of-
# absolute-differences heuristic over the five filter types, which is a pure
# function of the pixel data — same input, same filter choices, same bytes.

def _paeth(a, b, c):
    p = a + b - c
    pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
    if pa <= pb and pa <= pc:
        return a
    if pb <= pc:
        return b
    return c


def _filter_scanline(cur, prev, bpp):
    """(filter_type, filtered_bytes) for one scanline, best of the five."""
    n = len(cur)
    cands = []
    # 0 None
    cands.append((0, bytes(cur)))
    # 1 Sub
    sub = bytearray(n)
    for i in range(n):
        left = cur[i - bpp] if i >= bpp else 0
        sub[i] = (cur[i] - left) & 0xFF
    cands.append((1, bytes(sub)))
    # 2 Up
    up = bytearray(n)
    for i in range(n):
        up[i] = (cur[i] - prev[i]) & 0xFF
    cands.append((2, bytes(up)))
    # 3 Average
    avg = bytearray(n)
    for i in range(n):
        left = cur[i - bpp] if i >= bpp else 0
        avg[i] = (cur[i] - ((left + prev[i]) >> 1)) & 0xFF
    cands.append((3, bytes(avg)))
    # 4 Paeth
    pae = bytearray(n)
    for i in range(n):
        left = cur[i - bpp] if i >= bpp else 0
        ul = prev[i - bpp] if i >= bpp else 0
        pae[i] = (cur[i] - _paeth(left, prev[i], ul)) & 0xFF
    cands.append((4, bytes(pae)))
    best = None
    best_score = None
    for ftype, data in cands:
        # Signed-magnitude sum: bytes are treated as -128..127, the heuristic
        # the PNG spec itself recommends.
        score = sum(b if b < 128 else 256 - b for b in data)
        if best_score is None or score < best_score:
            best_score = score
            best = (ftype, data)
    return best


def _chunk(tag, payload):
    return (struct.pack(">I", len(payload)) + tag + payload
            + struct.pack(">I", binascii.crc32(tag + payload) & 0xFFFFFFFF))


def encode_png(width, height, rgb):
    """RGB8 pixel bytes -> a complete PNG file as ``bytes``.

    Exactly three chunks: IHDR, IDAT, IEND. No ``tIME``, no ``tEXt``, no
    ``pHYs`` — nothing that varies between runs.
    """
    if len(rgb) != width * height * 3:
        raise ValueError("pixel buffer is %d bytes, expected %d"
                         % (len(rgb), width * height * 3))
    bpp = 3
    stride = width * bpp
    raw = bytearray()
    prev = bytes(stride)
    for y in range(height):
        cur = rgb[y * stride:(y + 1) * stride]
        ftype, data = _filter_scanline(cur, prev, bpp)
        raw.append(ftype)
        raw += data
        prev = cur
    ihdr = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    return (b"\x89PNG\r\n\x1a\n"
            + _chunk(b"IHDR", ihdr)
            + _chunk(b"IDAT", zlib.compress(bytes(raw), 9))
            + _chunk(b"IEND", b""))


