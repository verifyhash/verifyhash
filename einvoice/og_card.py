#!/usr/bin/env python3
"""og_card.py — the 1200x630 link-preview card, drawn from Python source only.

WHY THIS FILE EXISTS. LinkedIn, XING, Slack, Reddit, Discord and the
ActivityPub clients render a shared URL as a card. WITH an ``og:image`` that
card is a large picture tile; without one it is a narrow text strip worth a
fraction of the feed real-estate. ``gen_site.py`` already emits the full
Open Graph / Twitter tag block on every sitemapped page; the image was the last
missing piece, and the announce is one-shot.

THE CONSTRAINT that shapes everything here: ZERO new dependencies, no network,
no vendored font binary, and nothing that cannot be regenerated byte-for-byte
from source. So this module is a tiny renderer:

  * a STROKE FONT (:data:`GLYPHS`) — each glyph is a list of polylines in a
    normalised em box (baseline ``y=0``, cap height ``y=1``, x growing right).
    Curved letters are sampled from ellipse arcs by :func:`_arc` at import
    time, so ``O``/``S``/``e`` are real curves rather than staircases. This is
    hand-authored SOURCE, not a font file: it is diffable, and it is the reason
    a scaled 5x7 bitmap font (which turns to pixel mush at 100px cap height)
    was not used.
  * an ANTIALIASED rasteriser (:func:`draw_text`) — coverage of a pixel is
    ``clamp(halfwidth + 0.5 - distance_to_stroke, 0, 1)``, i.e. an analytic
    distance field with round caps and joins. Coverage is accumulated per text
    run with ``max()`` before compositing, so overlapping strokes inside one
    glyph (the crossbar of ``e``, the junction of ``h``) do not darken twice
    into a visible seam.
  * a PNG WRITER (:func:`encode_png`) — ``zlib`` + ``struct`` +
    ``binascii.crc32``, emitting exactly IHDR, IDAT, IEND. There is
    deliberately NO ``tIME`` and no ``tEXt`` chunk: those are the two chunks
    that would make the file differ between two runs, and the generator's
    staleness gate compares the committed bytes to a fresh render.

DETERMINISM. Every number below is a literal or is derived from the package's
own :func:`einvoice.capabilities`; there is no clock, no randomness, no
environment read, and no dict-ordering dependence (the glyph table is only ever
looked up by key). Two consecutive :func:`render_card` calls in any process on
any machine with the same zlib produce identical bytes.

HONEST LIMITS. This is a monoline geometric sans with a single weight, no
kerning pairs (only a uniform tracking value), no hinting and no bidi/complex
shaping. It renders the ASCII subset in :data:`GLYPHS` and raises
:class:`KeyError` on anything else — a loud build failure, because a card with
a silently dropped character is worse than a failed build. It is sized for one
job (a 1200x630 card at 26-120px cap height) and is not a general text engine.

    python3 og_card.py out.png    # render the card standalone, for eyeballing
"""

