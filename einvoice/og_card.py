# Geometry helper: an ellipse arc sampled as a polyline.
#
# ``a0``/``a1`` are degrees, x = cx + rx*cos(a), y = cy + ry*sin(a) (y grows
# UP, as everywhere in the em box). The sweep runs from a0 towards a1 in the
# direction implied by their order, at <= ``step`` degrees per sample, so a
# quarter turn is 15 samples: far below the point where the round-capped
# stroke would show facets at card size. The sample count is computed with
# ``math.ceil`` on a literal, so it is the same everywhere.


def _arc(cx, cy, rx, ry, a0, a1, step=6.0):
    """Polyline of (x, y) points along an ellipse arc, endpoints included."""
    span = a1 - a0
    n = max(2, int(math.ceil(abs(span) / step)) + 1)
    pts = []
    for i in range(n):
        a = math.radians(a0 + span * i / (n - 1))
        pts.append((cx + rx * math.cos(a), cy + ry * math.sin(a)))
    return pts


