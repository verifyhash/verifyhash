# THE CARD ITSELF.
#
# 1200x630 is the size LinkedIn, X and Facebook all crop to (1.91:1); at that
# ratio nothing is trimmed on any of them. Colours are the SAME hexes the
# generated pages already use, so the card cannot look like a different
# product: #161b22 surface, #e6edf3 primary text, #8b949e muted, #4493f8
# accent.
CARD_WIDTH = 1200
CARD_HEIGHT = 630
_BG = (0x16, 0x1B, 0x22)
_FG = (0xE6, 0xED, 0xF3)
_MUTED = (0x8B, 0x94, 0x9E)
_ACCENT = (0x44, 0x93, 0xF8)


def render_card(title, standard, facts, source):
    """The card bytes.

    Every string is passed IN by the caller (``gen_site.py``), which reads
    them from the package's own :func:`einvoice.capabilities` and its BASE_URL
    constant — this module invents no fact and hard-codes no number.

    :param title: the product name, big.
    :param standard: the conformance line, e.g. the standards this checks.
    :param facts: the derived figures line (rule count, engine version).
    :param source: the site the card belongs to, as an eyebrow.
    """
    for name, value in (("title", title), ("standard", standard),
                        ("facts", facts), ("source", source)):
        if not value or not value.strip():
            raise ValueError("card %s is empty" % name)
    c = Canvas(CARD_WIDTH, CARD_HEIGHT, _BG)
    # A 10px accent band down the left edge: the one purely decorative
    # element, and the thing that makes the tile recognisable in a feed.
    c.fill_rect(0, 0, 10, CARD_HEIGHT, _ACCENT)

    margin = 96
    draw_text(c, source, margin, 168, 25, _MUTED, tracking=0.09)
    draw_text(c, title, margin, 320, 116, _FG)
    draw_text(c, standard, margin, 410, 44, _FG, tracking=0.005)
    c.fill_rect(margin, 456, 132, 5, _ACCENT)
    draw_text(c, facts, margin, 536, 31, _MUTED, tracking=0.02)
    return encode_png(CARD_WIDTH, CARD_HEIGHT, bytes(c.buf))


